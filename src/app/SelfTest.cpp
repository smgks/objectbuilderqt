namespace {
int g_fail = 0;
void check(bool ok, const char *what)
{
    std::fprintf(ok ? stdout : stderr, "%s: %s\n", ok ? "ok  " : "FAIL", what);
    if (!ok)
        ++g_fail;
}
} // namespace

// `ObjectBuilderQt --list-commands <file.md>`: writes every original menu item
// with its command id and whether a handler is registered.
int listCommands(MainWindow &w, const QString &outFile)
{
    QFile f(outFile);
    if (!f.open(QIODevice::WriteOnly | QIODevice::Text))
        return 1;
    QTextStream out(&f);
    int done = 0, total = 0;
    QStringList lines;
    std::function<void(const QJsonArray &, const QString &)> walk = [&](const QJsonArray &items, const QString &path) {
        for (const QJsonValue &v : items) {
            const QJsonObject o = v.toObject();
            QString text = o.value(QLatin1String("text")).toString().section(QLatin1Char('\t'), 0, 0).remove(QLatin1Char('&')).trimmed();
            text.replace(QLatin1String("&&"), QLatin1String("&"));
            if (o.contains(QLatin1String("items"))) {
                walk(o.value(QLatin1String("items")).toArray(), path.isEmpty() ? text : path + QStringLiteral(" > ") + text);
            } else if (o.contains(QLatin1String("id"))) {
                const int id = o.value(QLatin1String("id")).toInt();
                const bool has = w.registry()->has(id);
                ++total;
                done += has;
                lines << QStringLiteral("| %1 | %2 | %3 |").arg(has ? QStringLiteral("yes") : QStringLiteral("-"), QString::number(id), path + QStringLiteral(" > ") + text);
            }
        }
    };
    walk(w.uiSpec().mainMenu(), QString());
    out << "# Command coverage\n\nGenerated by `ObjectBuilderQt --list-commands`. "
        << done << " of " << total << " original main-menu commands have a handler.\n\n"
        << "| Done | ID | Menu path |\n|---|---|---|\n";
    for (const QString &l : lines)
        out << l << '\n';
    std::printf("%d/%d commands implemented\n", done, total);
    return 0;
}

int runSelfTest(MainWindow &w, const QString &outDir)
{
    QDir().mkpath(outDir);
    Document *d = w.document();
    CommandRegistry *r = w.registry();
    auto shot = [&](const QString &name) {
        QApplication::processEvents();
        w.grab().save(outDir + QLatin1Char('/') + name + QStringLiteral(".png"));
    };

    // Box at the pin, then select all / triangulate / undo.
    d->editActive(QStringLiteral("Create Primitive"), [&](ObjectData &o) {
        Primitives::Params p;
        p.sizeX = 2;
        p.sizeY = 1;
        p.sizeZ = 1;
        p.segX = 2;
        Primitives::box(o, p, w.creationFrame());
    });
    check(d->active().faces.size() == 10, "box with 2 X segments has 10 quads");
    r->trigger(Cmd::Deselect);
    check(d->active().selection.isEmpty(), "Deselect clears selection");
    r->trigger(Cmd::SelectAll);
    check(d->active().selection.faceCount() == 10, "Select All selects all faces");
    r->trigger(Cmd::TriangulateBack);
    check(d->active().faces.size() == 20, "Triangulate splits quads");
    r->trigger(Cmd::Undo);
    check(d->active().faces.size() == 10, "Undo restores quads");
    r->trigger(Cmd::Redo);
    check(d->active().faces.size() == 20, "Redo re-applies");
    r->trigger(Cmd::Undo);

    // Named selection via the data API + hide/unhide commands.
    r->trigger(Cmd::HideSelection);
    check(!d->active().hidden.isEmpty(), "Hide Selection hides");
    r->trigger(Cmd::Unhide);
    check(d->active().hidden.isEmpty(), "Unhide shows everything");

    // Copy / paste duplicates geometry.
    r->trigger(Cmd::SelectAll);
    r->trigger(Cmd::Copy);
    r->trigger(Cmd::Paste);
    check(d->active().faces.size() == 20 && d->active().points.size() == 2 * 12, "Copy+Paste duplicates");
    r->trigger(Cmd::Undo);

    // Extrude creates side faces around the selected region.
    d->editActive(QStringLiteral("select one face"), [](ObjectData &o) {
        o.selection.clear();
        o.selection.setFace(0, true);
        o.selectPointsFromFaces();
    });
    r->trigger(Cmd::Extrude);
    check(d->active().faces.size() == 14, "Extrude adds 4 side faces");
    r->trigger(Cmd::Undo);
    r->trigger(Cmd::Undo);

    // Mouse: rubber-band selection and Alt+drag freehand move, in two views,
    // to verify picking and the screen<->model axis mapping.
    r->trigger(Cmd::ZoomDrawing);
    QApplication::processEvents();
    auto mouse = [](QWidget *v, QEvent::Type t, QPoint p, Qt::MouseButton b, Qt::KeyboardModifiers m) {
        QMouseEvent e(t, QPointF(p), v->mapToGlobal(QPointF(p)), b, t == QEvent::MouseButtonRelease ? Qt::NoButton : b, m);
        QApplication::sendEvent(v, &e);
    };
    auto drag = [&](QWidget *v, QPoint a, QPoint b, Qt::KeyboardModifiers m) {
        mouse(v, QEvent::MouseButtonPress, a, Qt::LeftButton, m);
        mouse(v, QEvent::MouseMove, (a + b) / 2, Qt::LeftButton, m);
        mouse(v, QEvent::MouseMove, b, Qt::LeftButton, m);
        mouse(v, QEvent::MouseButtonRelease, b, Qt::LeftButton, m);
    };
    for (Viewport *v : w.viewports()) {
        if (v->viewType() != ViewType::Front && v->viewType() != ViewType::Left)
            continue;
        r->trigger(Cmd::Deselect);
        drag(v, QPoint(2, 2), QPoint(v->width() - 3, v->height() - 3), Qt::NoModifier);
        check(d->active().selection.pointCount() == 12, "rubber-band selects every point");
        const QVector<Point> before = d->active().points;
        const int undoCount = d->undoStack()->count();
        const QPoint c(v->width() / 2, v->height() / 2);
        drag(v, c, c + QPoint(40, 0), Qt::AltModifier);
        const QVector3D delta = d->active().points[0].pos - before[0].pos;
        if (v->viewType() == ViewType::Front)
            check(delta.x() > 0 && qFuzzyIsNull(delta.y()) && qFuzzyIsNull(delta.z()), "Front view: drag right moves +X");
        else
            check(delta.z() < 0 && qFuzzyIsNull(delta.x()) && qFuzzyIsNull(delta.y()), "Left view: drag right moves -Z");
        check(d->undoStack()->count() == undoCount + 1, "freehand drag is one undo step");
        r->trigger(Cmd::Undo);
    }

    // Views and display toggles.
    r->trigger(Cmd::ZoomDrawing);
    shot(QStringLiteral("01_wireframe"));
    r->trigger(Cmd::SolidFill);
    shot(QStringLiteral("02_solid"));
    r->trigger(Cmd::SolidFill);

    // LOD management through editAll.
    d->editAll(QStringLiteral("Add LOD"), [](LodObject &m) { m.active = m.addLod(LodNames::Geometry); });
    check(d->model().lods.size() == 2 && LodNames::name(d->model().activeResolution()) == QStringLiteral("Geometry"),
          "Geometry LOD added and active");
    r->trigger(Cmd::Undo);
    check(d->model().lods.size() == 1, "Undo removes the LOD");

    // Save / reload round trip through the document.
    const QString file = outDir + QStringLiteral("/selftest.p3d");
    QString err;
    check(d->save(file, &err), "save");
    check(d->open(file, &err) && d->active().faces.size() == 10, "reopen");

    // Dialog layouts.
    r->trigger(Cmd::SelectAll);
    {
        FacePropertiesDialog dlg(d, &w);
        dlg.show();
        QApplication::processEvents();
        dlg.grab().save(outDir + QStringLiteral("/03_face_properties.png"));
    }
    {
        PointPropertiesDialog dlg(d, &w);
        dlg.show();
        QApplication::processEvents();
        dlg.grab().save(outDir + QStringLiteral("/04_point_properties.png"));
    }
    shot(QStringLiteral("05_final"));
    std::printf("%s\n", g_fail ? "SELFTEST FAILED" : "SELFTEST PASSED");
    std::fflush(stdout);
    return g_fail ? 1 : 0;
}

// `ObjectBuilderQt --screenshot <model or game path> <out.png> [viewType]`:
// opens a model in solid textured view and saves a window capture once the
// textures are loaded. Used to check imports visually.
int runScreenshot(MainWindow &w, const QString &model, const QString &outFile)
{
    ViewSettings *vs = w.viewSettings();
    vs->solid = true;
    vs->textured = true;
    vs->culling = qEnvironmentVariableIsSet("OB_SHOT_CULL");
    QElapsedTimer t;
    t.start();
    while (!GameData::instance().isIndexed() && t.elapsed() < 30000)
        QApplication::processEvents(QEventLoop::AllEvents, 50);
    const bool ok = QFileInfo::exists(model) ? w.openFile(model) : w.openGameFile(model);
    if (!ok)
        return 1;
    // show the surfaces, not a stored selection (not saved: the shot only views)
    w.document()->editAll(QStringLiteral("Deselect"), [](LodObject &m) {
        for (Lod &l : m.lods)
            l.data.selection.clear();
    });
    // let the viewports request textures, then wait for the decodes
    for (int i = 0; i < 3; ++i) {
        w.refreshViews();
        QApplication::processEvents(QEventLoop::AllEvents, 50);
    }
    QSet<QString> textures;
    for (const Face &f : w.document()->active().faces)
        if (!f.texture.isEmpty())
            textures.insert(f.texture);
    t.restart();
    while (t.elapsed() < 20000) {
        bool all = true;
        for (const QString &tx : textures)
            all &= TextureLibrary::instance().isCached(tx);
        QApplication::processEvents(QEventLoop::AllEvents, 50);
        if (all)
            break;
    }
    // OB_SHOT_FOCUS=<named selection>: frame that selection in every view.
    const QString focus = qEnvironmentVariable("OB_SHOT_FOCUS");
    if (const NamedSelection *ns = focus.isEmpty() ? nullptr : w.document()->active().findSelection(focus)) {
        const ObjectData &o = w.document()->active();
        QVector3D mn(1e30f, 1e30f, 1e30f), mx(-1e30f, -1e30f, -1e30f);
        for (int i = 0; i < o.points.size(); ++i)
            if (ns->sel.point(i)) {
                mn = QVector3D(std::min(mn.x(), o.points[i].pos.x()), std::min(mn.y(), o.points[i].pos.y()), std::min(mn.z(), o.points[i].pos.z()));
                mx = QVector3D(std::max(mx.x(), o.points[i].pos.x()), std::max(mx.y(), o.points[i].pos.y()), std::max(mx.z(), o.points[i].pos.z()));
            }
        if (mn.x() <= mx.x())
            for (Viewport *v : w.viewports())
                v->zoomToBox(mn, mx);
    }
    for (int i = 0; i < 5; ++i) {
        w.refreshViews();
        QApplication::processEvents(QEventLoop::AllEvents, 100);
    }
    w.grab().save(outFile);
    std::printf("saved %s (%d textures)\n", qPrintable(outFile), int(textures.size()));
    std::fflush(stdout);
    return 0;
}
